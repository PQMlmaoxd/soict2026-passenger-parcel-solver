//! The contest accepts one C++ file. This module builds that file from `src/`
//! and proves that it is the program that was submitted.
//!
//! * [`amalgamate`] replaces each local `#include "module.hpp"` of `main.cpp`
//!   by the text of the module. The result is one translation unit, which is
//!   what the compiler sees in the modular build too.
//! * [`token_stream`] preprocesses a file and removes all whitespace. Comments
//!   are gone after preprocessing, `#pragma once` and local includes are
//!   resolved, so two files with the same token stream are the same program.
//! * [`assembly`] compiles to assembly. Equal assembly is the strongest check
//!   and is meant for the same compiler on both sides.

use std::collections::HashSet;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Header of a generated file.
pub const BANNER: &str = "// Generated by the `amalgamate` tool from src/. Do not edit this file;\n// edit the modules and regenerate.\n";

/// Lines of `path` with local includes replaced, each module at most once.
fn expand(path: &Path, seen: &mut HashSet<PathBuf>, lines: &mut Vec<String>) -> io::Result<()> {
    let path = path.canonicalize()?;
    if !seen.insert(path.clone()) {
        return Ok(());
    }
    let directory = path.parent().unwrap_or_else(|| Path::new("."));
    for line in fs::read_to_string(&path)?.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("#include \"") {
            if let Some(name) = rest.strip_suffix('"') {
                expand(&directory.join(name), seen, lines)?;
                continue;
            }
        }
        if trimmed != "#pragma once" {
            lines.push(line.to_string());
        }
    }
    Ok(())
}

/// Single-file text of the program whose entry point is `entry`.
pub fn amalgamate(entry: &Path) -> io::Result<String> {
    let mut lines = Vec::new();
    expand(entry, &mut HashSet::new(), &mut lines)?;
    Ok(format!("{BANNER}{}\n", lines.join("\n")))
}

fn run_compiler(compiler: &str, args: &[&str]) -> io::Result<String> {
    let output = Command::new(compiler).args(args).output()?;
    if !output.status.success() {
        return Err(io::Error::other(format!(
            "{compiler} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        )));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

/// Preprocessed text of `file` with every whitespace character removed.
pub fn token_stream(compiler: &str, file: &Path) -> io::Result<String> {
    let include = file.parent().unwrap_or_else(|| Path::new("."));
    let include_flag = format!("-I{}", include.display());
    let text = run_compiler(
        compiler,
        &[
            "-std=c++17",
            "-E",
            "-P",
            &include_flag,
            &file.display().to_string(),
        ],
    )?;
    Ok(text.chars().filter(|c| !c.is_whitespace()).collect())
}

/// Assembly of `file` at -O2, without the lines that only name the source file.
pub fn assembly(compiler: &str, file: &Path) -> io::Result<String> {
    let include = file.parent().unwrap_or_else(|| Path::new("."));
    let include_flag = format!("-I{}", include.display());
    let text = run_compiler(
        compiler,
        &[
            "-std=c++17",
            "-O2",
            "-S",
            &include_flag,
            "-o",
            "-",
            &file.display().to_string(),
        ],
    )?;
    Ok(text
        .lines()
        .filter(|line| {
            let line = line.trim_start();
            !line.starts_with(".file") && !line.starts_with(".ident")
        })
        .collect::<Vec<_>>()
        .join("\n"))
}

/// Index of the first differing character, or `None` when the texts are equal.
pub fn first_difference(a: &str, b: &str) -> Option<usize> {
    let common = a.chars().zip(b.chars()).position(|(x, y)| x != y);
    match common {
        Some(index) => Some(index),
        None if a.chars().count() == b.chars().count() => None,
        None => Some(a.chars().count().min(b.chars().count())),
    }
}

/// A short window of `text` around character `at`, for error messages.
pub fn excerpt(text: &str, at: usize) -> String {
    text.chars().skip(at.saturating_sub(60)).take(120).collect()
}
